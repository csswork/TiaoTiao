#!/usr/bin/env python3
"""Regenerate the Android launcher resources from the selected TiaoTiao logo master."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

PROJECT = Path(__file__).resolve().parents[1]
DRAWABLE = PROJECT / "app/src/main/res/drawable"
BRANDING = PROJECT / "artifacts/branding"
SOURCE = BRANDING / "tiaotiao-logo-interlock.svg"
NS = "{http://www.w3.org/2000/svg}"
FULL = "M0 0H108V108H0Z"


def argb(color, opacity="1"):
    return "#%02X%s" % (round(float(opacity) * 255), color.lstrip("#").upper())


def main():
    source = ET.parse(SOURCE).getroot()
    defs = {g.attrib["id"]: g for g in source.find(NS + "defs")}
    tile = source.find(NS + "path").attrib["d"]
    group = source.find(NS + "g")
    standalone_scale = re.search(r"scale\(([\d.]+)\)", group.attrib["transform"]).group(1)
    marks = [(p.attrib["fill"], p.attrib["d"]) for p in group]

    green, glow = defs["green"], defs["glow"]
    g0, g1 = [s.attrib["stop-color"] for s in green]
    linear = (f'<gradient android:type="linear" android:startX="{green.attrib["x1"]}" android:startY="{green.attrib["y1"]}" '
              f'android:endX="{green.attrib["x2"]}" android:endY="{green.attrib["y2"]}" '
              f'android:startColor="{g0}" android:endColor="{g1}" />')
    h0, h1 = [argb(s.attrib["stop-color"], s.attrib.get("stop-opacity", "1")) for s in glow]
    radial = (f'<gradient android:type="radial" android:centerX="{glow.attrib["cx"]}" android:centerY="{glow.attrib["cy"]}" '
              f'android:gradientRadius="{glow.attrib["r"]}" android:startColor="{h0}" android:endColor="{h1}" />')

    def vector(background=None, monochrome=False, mark=True, scale="1"):
        lines = ['<!-- Deployed TiaoTiao brand. Generated by tools/generate_brand_assets.py. -->',
                 '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"',
                 '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
        if background:
            for gradient in (linear, radial):
                lines += [f'    <path android:pathData="{background}">',
                          '        <aapt:attr name="android:fillColor">',
                          f'            {gradient}',
                          '        </aapt:attr>', '    </path>']
        if mark:
            indent = "    "
            if scale != "1":
                lines.append(f'    <group android:scaleX="{scale}" android:scaleY="{scale}" android:pivotX="54" android:pivotY="54">')
                indent = "        "
            for color, path in marks:
                lines.append(f'{indent}<path android:fillColor="{("#FFFFFF" if monochrome else color)}" android:pathData="{path}" />')
            if scale != "1":
                lines.append('    </group>')
        lines.append('</vector>')
        return '\n'.join(lines) + '\n'

    (DRAWABLE / "ic_launcher.xml").write_text(vector(tile, scale=standalone_scale))
    (DRAWABLE / "ic_brand_background.xml").write_text(vector(FULL, mark=False))
    (DRAWABLE / "ic_brand_foreground.xml").write_text(vector())
    (DRAWABLE / "ic_brand_monochrome.xml").write_text(vector(monochrome=True))
    (BRANDING / "tiaotiao-logo.svg").write_text(SOURCE.read_text())
    print(f"Regenerated launcher resources from {SOURCE.name}")


if __name__ == "__main__":
    main()
