#!/usr/bin/env python3
"""Regenerate the deployed 0.2.5 brand; subsequent logo studies remain shelved."""
from pathlib import Path
import xml.etree.ElementTree as ET

PROJECT = Path(__file__).resolve().parents[1]
DRAWABLE = PROJECT / "app/src/main/res/drawable"
BRANDING = PROJECT / "artifacts/branding"
SOURCE = BRANDING / "tiaotiao-logo-0.2.5.svg"
NS = "{http://www.w3.org/2000/svg}"


def main():
    source = ET.parse(SOURCE).getroot()
    tile = source.find(NS + "path").attrib["d"]
    marks = [(p.attrib["fill"], p.attrib["d"]) for p in source.find(NS + "g")]
    def vector(background=None, monochrome=False, mark=True):
        lines = ['<!-- Deployed TiaoTiao brand. Generated by tools/generate_brand_assets.py. -->',
                 '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"',
                 '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
        if background:
            lines += [f'    <path android:pathData="{background}">',
                      '        <aapt:attr name="android:fillColor">',
                      '            <gradient android:type="linear" android:startX="12" android:startY="0" android:endX="100" android:endY="108" android:startColor="#2E795B" android:endColor="#123F32" />',
                      '        </aapt:attr>', '    </path>']
        if mark:
            lines.append('    <group android:scaleX="0.86" android:scaleY="0.86" android:pivotX="54" android:pivotY="54">')
            for color, path in marks:
                lines.append(f'        <path android:fillColor="{("#FFFFFF" if monochrome else color)}" android:pathData="{path}" />')
            lines.append('    </group>')
        lines.append('</vector>')
        return '\n'.join(lines) + '\n'
    (DRAWABLE / "ic_launcher.xml").write_text(vector(tile))
    (DRAWABLE / "ic_brand_background.xml").write_text(vector("M0 0H108V108H0Z", mark=False))
    (DRAWABLE / "ic_brand_foreground.xml").write_text(vector())
    (DRAWABLE / "ic_brand_monochrome.xml").write_text(vector(monochrome=True))
    (BRANDING / "tiaotiao-logo.svg").write_text(SOURCE.read_text())
    print("Restored deployed brand resources; no new logo design is shipped")


if __name__ == "__main__":
    main()
